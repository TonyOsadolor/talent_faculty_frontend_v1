// Deterministic fallback generator so every user (not just the two hero
// profiles above) has something reasonable to show on their profile page.
export const buildInstructorProfile = (user: AppUser): InstructorProfileDetail => {
  if (instructorProfiles[user.id]) return instructorProfiles[user.id]

  const seed = user.name.length
  return {
    totalLearners: 40 + seed * 6,
    cohorts: 1,
    totalCourses: 2,
    avgCompletionRate: `${50 + (seed % 40)}%`,
    assessments: 8 + (seed % 10),
    passRate: `${45 + (seed % 40)}%`,
    courses: [
      {
        id: `${user.id}-c1`,
        title: 'Introduction to HTML',
        lessons: 25,
        modules: 7,
        status: 'In Progress',
        learners: 30 + seed,
        cohort: user.cohort ?? 'Cohort 1A',
        progress: 40 + (seed % 50),
        courseCompletion: `${60 + (seed % 30)}%`,
        assessmentCompletion: `${55 + (seed % 30)}%`,
        passRate: `${40 + (seed % 30)}%`,
      },
    ],
    cohortDetails: [
      {
        label: 'First Cohort',
        cohort: user.cohort ?? 'Cohort 1A',
        programType: 'Professional Training',
        status: 'Active',
        startDate: 'January 20th, 2026',
        expectedCompletion: 'June 2nd, 2026',
        completionRate: 40 + (seed % 50),
      },
    ],
    activities: [
      { activity: 'Logged in', type: 'Login', time: 'August 1st, 2026' },
    ],
  }
}

